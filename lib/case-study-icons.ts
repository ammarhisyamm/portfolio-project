const BY_LABEL: Record<string, string> = {
  problem: "puzzle",
  approach: "compass",
  "my role": "user",
  outcome: "flag",
  status: "activity",
  team: "users",
  timeline: "calendar",
  language: "languages",
  device: "phone",
  standardise: "list-checks",
  monitor: "gauge",
  budget: "wallet",
  risk: "shield",
  "impact summary": "trend",
  "what comes next": "route",
  next: "route",
  shipped: "package",
  access: "key",
  "research in the defaults": "pin",
};

export function cardIcon(card: Pick<CaseStudyCard, "icon" | "label">): LucideIcon | null {
  const key = card.icon ?? BY_LABEL[(card.label ?? "").trim().toLowerCase()];
  return key ? CASE_STUDY_ICONS[key] ?? null : null;
}
